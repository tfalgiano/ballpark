/* Regenerates tests/published-schedule.json — the record of the schedule we
   INTEND to have shipped. tests/test.js diffs the live pack against it, so this
   file is the thing that makes an unintended change fail loudly.

   Because it is the reference, regenerating it can also launder a corruption
   into the "expected" state. So it refuses to record any change to a day at or
   before today's index. Today counts as played: the day rolls over on each
   player's own clock, so somewhere in UTC+14 today's puzzle was answered hours
   ago.

   Run AFTER an intentional schedule change (a content append, or an approved
   amendment), never to make a failing test pass.
   Run: node tools/freeze-schedule.js */
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const crypto = require("node:crypto");

const ROOT = path.join(__dirname, "..");
const RECORD = path.join(ROOT, "tests", "published-schedule.json");

const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(ROOT, "puzzles.js"), "utf8"), sandbox);
const D = sandbox.window.BALLPARK_DATA;

const prev = fs.existsSync(RECORD) ? JSON.parse(fs.readFileSync(RECORD, "utf8")) : null;
const hash = (s) => crypto.createHash("sha256").update(s, "utf8").digest("hex").slice(0, 12);

const [y, m, d] = D.epoch.split("-").map(Number);
const now = new Date();
const today = Math.floor(
  (Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) - Date.UTC(y, m - 1, d)) / 864e5);

if (prev) {
  if (prev.epoch !== D.epoch) {
    console.error(`REFUSING: epoch moved ${prev.epoch} -> ${D.epoch}. Every past day would shift.`);
    process.exit(1);
  }
  const violations = [];
  const limit = Math.min(today, prev.days.length - 1);
  for (let i = 0; i <= limit; i++) {
    if ((D.days[i] || []).join() !== prev.days[i].join()) {
      violations.push(`day ${i} (puzzle #${i + 1})\n      was: ${prev.days[i].join(", ")}\n      now: ${(D.days[i] || []).join(", ")}`);
    }
  }
  for (const [id, want] of Object.entries(prev.promptHashes)) {
    const day = prev.days.findIndex((dd) => dd.indexOf(id) >= 0);
    if (day < 0 || day > today) continue;              // only guard played days
    const q = D.questions[id];
    if (!q) { violations.push(`${id} (played on day ${day}) no longer exists`); continue; }
    if (hash(q.prompt) !== want) violations.push(`${id} (played on day ${day}) changed its prompt`);
  }
  if (violations.length) {
    console.error(`\nREFUSING TO FREEZE - ${violations.length} change(s) to ALREADY-PLAYED content:\n`);
    for (const v of violations) console.error("  - " + v);
    console.error("\nPlayed content is immutable. This tool records intent; it must never be\n" +
      "used to make a failing immutability test pass.\n");
    process.exit(1);
  }
  const changedFuture = [];
  for (let i = today + 1; i < Math.min(D.days.length, prev.days.length); i++) {
    if (D.days[i].join() !== prev.days[i].join()) changedFuture.push(i);
  }
  if (changedFuture.length) {
    console.log(`recording ${changedFuture.length} amended future day(s): ${changedFuture.join(", ")}`);
  }
  if (D.days.length > prev.days.length) {
    console.log(`recording ${D.days.length - prev.days.length} newly appended day(s)`);
  }
}

const promptHashes = {};
for (const id of D.days.flat()) promptHashes[id] = hash(D.questions[id].prompt);

fs.writeFileSync(RECORD, JSON.stringify({
  _comment: "Frozen record of every Ballpark day that has been published. Generated by " +
    "tools/freeze-schedule.js, which refuses to record any change to a day at or before " +
    "today's index. A day at or before today has been played, is cached in service workers, " +
    "and is addressable by ?d= challenge links - it must never change. tests/test.js diffs " +
    "the live pack against this. Amendments to FUTURE days go through " +
    "data/schedule-amendments.json and are reviewable there.",
  epoch: D.epoch,
  frozenAt: new Date(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()))
    .toISOString().slice(0, 10),
  frozenThroughDayIndex: D.days.length - 1,
  playedThroughDayIndexAtFreeze: today,
  days: D.days,
  promptHashes,
}, null, 1));

console.log(`froze ${D.days.length} days, ${Object.keys(promptHashes).length} prompt hashes ` +
  `(played through day index ${today})`);
